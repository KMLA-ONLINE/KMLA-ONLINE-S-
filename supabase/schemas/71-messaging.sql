-- 메시지 첨부(기능 명세 §13.5, Storage 설계 §4.4). object는 원본 그대로 비공개 버킷에 두고, 원본 파일
-- 이름은 이 행의 암호문 열에만 둔다. 업로드할 정확한 경로를 `prepare_message_attachments`가 `pending`
-- 행으로 예고하고, `send_message`가 object를 확인한 뒤 `ready`로 올린다. 메시지 행은 전송 때 생기므로
-- `message_id`는 외래 키가 아니다. 지우면 `deleted`로 두고 Storage 정리 작업이 행과 object를 회수한다.
create table private.message_attachments (
  id uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  message_id uuid not null,
  uploader_id bigint references public.profiles(id) on delete set null,
  status text not null default 'pending',
  position smallint not null,
  kind text not null,
  mime_type text not null,
  size_bytes bigint not null,
  width integer,
  height integer,
  object_path text not null unique,
  -- 사진의 목록용 축소본. 축소본 업로드가 실패하면 비어 있고 그때는 원본을 그린다.
  thumbnail_path text unique,
  filename_ciphertext bytea not null,
  key_version smallint not null,
  created_at timestamptz not null default now(),
  constraint message_attachments_status_check
    check (status in ('pending', 'ready', 'deleted')),
  constraint message_attachments_kind_check
    -- 동영상은 지원하지 않는다(기능 명세 §13.5). 예전에 올린 동영상은 일반 파일로 남긴다.
    check (kind in ('image', 'audio', 'file')),
  constraint message_attachments_mime_check
    check (char_length(mime_type) between 1 and 255),
  -- 정규화한 사진은 WebP 8MiB, 그 밖의 파일은 30MiB까지다(Storage 설계 §6).
  constraint message_attachments_size_check
    check (
      size_bytes > 0
      and size_bytes <= case when kind = 'image' then 8388608 else 31457280 end
    ),
  constraint message_attachments_image_check
    check (
      kind <> 'image'
      or (mime_type = 'image/webp' and width between 1 and 3072 and height between 1 and 3072)
    )
);

-- 같은 메시지 ID로 다시 예고하면 이전 행을 `deleted`로 두고 같은 순서로 새 행을 만든다. 순서는 지우지
-- 않은 행끼리만 겹치지 않으면 된다.
create unique index message_attachments_position_key
  on private.message_attachments (message_id, position)
  where status <> 'deleted';

create index message_attachments_message_idx
  on private.message_attachments (message_id);

create index message_attachments_conversation_idx
  on private.message_attachments (conversation_id, created_at desc)
  where status = 'ready';

