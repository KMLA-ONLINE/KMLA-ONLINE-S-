create function public.open_direct_conversation(p_profile_id bigint)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_profile_id bigint := private.current_profile_id();
  low_id bigint;
  high_id bigint;
  conversation_id uuid;
  joined timestamptz;
begin
  if caller_profile_id is null then
    raise exception 'accepted profile required'
      using errcode = '42501';
  end if;
  if p_profile_id is null or p_profile_id = caller_profile_id then
    raise exception 'another profile required'
      using errcode = '22023';
  end if;
