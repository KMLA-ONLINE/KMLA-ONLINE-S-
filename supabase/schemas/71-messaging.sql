-- 메시지(기능 명세 §13, 기술 설계 docs/MESSAGING_TECHNICAL_DESIGN.md).
--
-- 대화, 멤버의 참여 기간, 암호화한 메시지를 둔다. 세 테이블 모두 client grant가 없고, 읽기와 쓰기는
-- 호출자를 검증하는 아래 RPC로만 한다. 본문 복호화가 RPC 안에서만 일어나야 하기 때문이다.
--
-- 볼 수 있는 메시지는 "읽는 사람의 참여 기간 중 하나에 `sent_at`이 들어가는 메시지"다. 새 멤버의
-- 참여 이전 메시지와 나간 멤버의 이후 메시지를 이 조건 하나로 함께 막는다. 이 판정은 RPC마다 풀어
-- 쓴다. 행마다 함수를 부르면 페이지 하나에 수십 번의 조회가 붙는다.

create type public.conversation_type as enum ('direct', 'group');

create table public.conversations (
  id uuid primary key default gen_random_uuid(),
  type public.conversation_type not null,
  -- 그룹 대화의 이름. 1:1 대화는 상대 이름을 표시하므로 비워 둔다.
  name text,
  created_by bigint references public.profiles(id) on delete set null,
  -- 1:1 대화의 두 프로필. 작은 ID를 앞에 두어 같은 두 사람 사이에 대화가 하나만 생기게 한다.
  direct_profile_low bigint references public.profiles(id) on delete cascade,
  direct_profile_high bigint references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint conversations_kind_check
    check (
      (
        type = 'direct'
        and name is null
        and direct_profile_low is not null
        and direct_profile_high is not null
        and direct_profile_low < direct_profile_high
      )
      or (
        type = 'group'
        and char_length(btrim(name)) between 1 and 50
        and direct_profile_low is null
        and direct_profile_high is null
      )
    ),
  constraint conversations_direct_pair_key
    unique (direct_profile_low, direct_profile_high)
);

-- 멤버십은 참여 기간 하나가 한 행이다. 나가면 `left_at`을 채우고, 다시 참여하면 새 행을 만든다.
-- 읽음 위치와 알림 설정은 기간마다 따로 두며, 화면은 가장 최근 기간의 값을 쓴다.
create table public.conversation_members (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  -- 참여·나간 시각은 메시지 `sent_at`과 같은 시계(`clock_timestamp()`)로 적는다. 트랜잭션 시작
  -- 시각(`now()`)을 쓰면 잠금을 기다린 사이에 커밋된 메시지가 경계의 반대편에 놓인다.
  joined_at timestamptz not null default clock_timestamp(),
  left_at timestamptz,
  -- 마지막으로 읽은 메시지의 `(sent_at, id)`. 참여 시각에서 시작하므로 참여 이전 메시지는 읽지
  -- 않은 수에 들어가지 않는다. nil UUID는 같은 시각의 어떤 메시지보다도 앞선다. 멤버를 넣는 RPC는
  -- 참여 시각과 같은 값을 넣는다.
  last_read_sent_at timestamptz not null default clock_timestamp(),
  last_read_message_id uuid not null default '00000000-0000-0000-0000-000000000000',
  muted_until timestamptz,
  -- 스스로 나간 기간인지. 내보내진 기간과 달리 대화 목록에서 감춘다(기능 명세 §13.16).
  left_by_self boolean not null default false,
  constraint conversation_members_period_check
    check (left_at is null or left_at >= joined_at),
  constraint conversation_members_left_by_self_check
    check (not left_by_self or left_at is not null)
);

create unique index conversation_members_active_key
  on public.conversation_members (conversation_id, profile_id)
  where left_at is null;

create index conversation_members_profile_idx
  on public.conversation_members (profile_id, conversation_id, joined_at desc);

-- `id`는 클라이언트가 만든 UUID다. 같은 값으로 다시 보내면 한 번만 저장한다.
create table private.messages (
  id uuid primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id bigint references public.profiles(id) on delete set null,
  sent_at timestamptz not null default now(),
  reply_to_id uuid,
  -- pgcrypto `pgp_sym_encrypt` 결과와 그때 쓴 Vault 키의 버전. 삭제하면 둘 다 지운다.
  body_ciphertext bytea,
  key_version smallint,
  edited_at timestamptz,
  deleted_at timestamptz,
  -- 화면에 보이는 무엇이든 마지막으로 바뀐 시각. 수정, 삭제, 반응, 고정이 trigger로 갱신한다.
  -- 따라잡기 RPC가 이 시각으로 바뀐 메시지를 고른다(기술 설계 §5).
  changed_at timestamptz not null default clock_timestamp(),
  -- 멤버 추가·나가기·내보내기·이름 변경을 대화 안에 남기는 시스템 메시지(기능 명세 §13.17). 본문이
  -- 없고, 화면 문구는 클라이언트가 종류와 대상 프로필, 새 이름으로 만든다. 대화 참여자와 그룹 이름은
  -- 암호화 대상이 아니다(기능 명세 §13.20).
  system_kind text,
  system_profile_ids bigint[],
  system_name text,
  constraint messages_conversation_id_key unique (conversation_id, id),
  -- 답장 대상은 같은 대화의 메시지다. 원본은 삭제해도 행을 남기므로 지워지지 않는다.
  constraint messages_reply_to_fkey
    foreign key (conversation_id, reply_to_id)
    references private.messages (conversation_id, id),
  constraint messages_body_check
    check (
      (body_ciphertext is null) = (key_version is null)
      and (
        (system_kind is null and (deleted_at is null) = (body_ciphertext is not null))
        or (system_kind is not null and body_ciphertext is null and deleted_at is null)
      )
    ),
  constraint messages_system_check
    check (
      (system_kind is null and system_profile_ids is null and system_name is null)
      or (
        system_kind in ('member_added', 'member_left', 'member_removed', 'renamed')
        and sender_id is null
        and reply_to_id is null
        and (system_kind = 'renamed') = (system_name is not null)
      )
    )
);

create index messages_conversation_sent_idx
  on private.messages (conversation_id, sent_at desc, id desc);

create index messages_conversation_changed_idx
  on private.messages (conversation_id, changed_at);

