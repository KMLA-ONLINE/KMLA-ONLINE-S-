-- 내 메시지를 지운다(기능 명세 §13.11). 행은 답장 인용이 가리키므로 남기고 본문, 반응, 고정을
-- 지운다. 하나라도 내 메시지가 아니면 아무것도 지우지 않고, 이미 지운 메시지는 건너뛴다. 나간
