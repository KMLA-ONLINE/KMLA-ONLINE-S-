  from public;

-- 내 반응을 정하거나(`p_reaction`) 지운다(`null`). 바뀐 뒤의 반응 집계를 돌려준다.
create function public.set_message_reaction(
  p_message_id uuid,
  p_reaction public.post_reaction default null
)
returns table (reactions jsonb, my_reaction public.post_reaction)
language plpgsql
security definer
set search_path = ''
as $$
