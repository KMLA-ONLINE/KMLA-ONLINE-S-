-- Vault의 메시지 키 전부를 `{"<버전>": "<secret>"}`로 돌려준다. 이름은 `message_key_v<버전>`이다.
-- RPC가 호출당 한 번 불러 그 호출이 다루는 모든 행에 쓴다. 키를 교체하면 새 버전을 추가하고, 이전
-- 버전은 남은 행을 다시 암호화할 때까지 복호화용으로 둔다.
create function private.message_keys()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  keys jsonb;
begin
  select jsonb_object_agg(
    substring(secret.name from '^message_key_v([0-9]+)$'),
    secret.decrypted_secret
  )
  into keys
  from vault.decrypted_secrets as secret
  where secret.name ~ '^message_key_v[0-9]+$';

  if keys is null then
    raise exception 'message encryption key missing'
      using errcode = '55000';
  end if;

  return keys;
end;
$$;

revoke all on function private.message_keys()
  from public;

-- 키가 무작위 고엔트로피 값이므로 비밀번호용 반복 키 유도는 끈다(`s2k-mode=1`). PGP 형식은
-- 변조 검사(MDC)를 포함한다. 반복 키 유도를 켜면 메시지 한 건 복호화가 약 0.3ms 걸려 한 페이지가
-- 눈에 띄게 느려진다.
create function private.encrypt_message_text(p_text text, p_keys jsonb)
returns table (ciphertext bytea, key_version smallint)
language sql
volatile
set search_path = ''
as $$
  select
    extensions.pgp_sym_encrypt(
      p_text, p_keys ->> current_key.version::text, 's2k-mode=1, cipher-algo=aes256'
    ),
    current_key.version
  from (
    select max(key::smallint) as version
    from jsonb_object_keys(p_keys) as key
  ) as current_key;
$$;

revoke all on function private.encrypt_message_text(text, jsonb)
  from public;

create function private.decrypt_message_text(
  p_ciphertext bytea,
  p_key_version smallint,
  p_keys jsonb
)
returns text
language sql
immutable
set search_path = ''
as $$
  select extensions.pgp_sym_decrypt(p_ciphertext, p_keys ->> p_key_version::text);
$$;

revoke all on function private.decrypt_message_text(bytea, smallint, jsonb)
  from public;

-- 내 대화 목록. `p_conversation_id`를 주면 그 대화 한 건만 돌려주며, 대화방이 대화 정보를 읽을 때
-- 쓴다. 나간 대화도 참여 기간의 메시지를 계속 볼 수 있으므로 목록에 남는다(기능 명세 §13.16).
create function public.list_conversations(p_conversation_id uuid default null)
returns table (
  conversation_id uuid,
  type public.conversation_type,
  name text,
  viewer_id bigint,
  -- 현재 멤버의 `{id, name, avatar_path}`. 참여 순서다.
  participants jsonb,
  last_message_id uuid,
  last_message_sender_id bigint,
  last_message_body text,
  last_message_sent_at timestamptz,
  last_message_deleted boolean,
  unread_count integer,
  muted boolean
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  caller_profile_id bigint := private.current_profile_id();
  keys jsonb;
begin
  if caller_profile_id is null then
    raise exception 'accepted profile required'
      using errcode = '42501';
  end if;

  keys := private.message_keys();

  return query
  with latest_period as (
    -- 대화마다 가장 최근 참여 기간. 읽음 위치와 알림 설정은 이 행의 값을 쓴다.
    select distinct on (member.conversation_id) member.*
    from public.conversation_members as member
    where member.profile_id = caller_profile_id
      and (p_conversation_id is null or member.conversation_id = p_conversation_id)
    order by member.conversation_id, member.joined_at desc
  )
  select
    conversation.id,
    conversation.type,
    coalesce(conversation.name, counterpart.name),
    caller_profile_id,
    coalesce(members.list, '[]'::jsonb),
    last_message.id,
    last_message.sender_id,
    case
      when last_message.deleted_at is null and last_message.id is not null
        then private.decrypt_message_text(
          last_message.body_ciphertext, last_message.key_version, keys
        )
    end,
    last_message.sent_at,
    last_message.deleted_at is not null,
    coalesce(unread.count, 0)::integer,
    coalesce(latest_period.muted_until > now(), false)
  from latest_period
  join public.conversations as conversation
    on conversation.id = latest_period.conversation_id
  left join public.profiles as counterpart
    on conversation.type = 'direct'
    and counterpart.id = case
      when conversation.direct_profile_low = caller_profile_id
        then conversation.direct_profile_high
      else conversation.direct_profile_low
    end
  left join lateral (
    select jsonb_agg(
      jsonb_build_object(
        'id', profile.id,
        'name', profile.name,
        'avatar_path', profile.avatar_path
      )
      order by member.joined_at, member.id
    ) as list
    from public.conversation_members as member
    join public.profiles as profile on profile.id = member.profile_id
    where member.conversation_id = conversation.id
      and member.left_at is null
  ) as members on true
  left join lateral (
    select message.*
    from private.messages as message
    where message.conversation_id = conversation.id
      and exists (
        select 1
        from public.conversation_members as period
        where period.conversation_id = conversation.id
          and period.profile_id = caller_profile_id
          and message.sent_at >= period.joined_at
          and (period.left_at is null or message.sent_at < period.left_at)
      )
    order by message.sent_at desc, message.id desc
    limit 1
  ) as last_message on true
  left join lateral (
    select count(*) as count
    from private.messages as message
    where message.conversation_id = conversation.id
      and message.sender_id is distinct from caller_profile_id
      and message.deleted_at is null
      and (message.sent_at, message.id)
        > (latest_period.last_read_sent_at, latest_period.last_read_message_id)
      and exists (
        select 1
        from public.conversation_members as period
        where period.conversation_id = conversation.id
          and period.profile_id = caller_profile_id
          and message.sent_at >= period.joined_at
          and (period.left_at is null or message.sent_at < period.left_at)
      )
  ) as unread on true
  order by last_message.sent_at desc nulls last, conversation.created_at desc, conversation.id;
end;
$$;

revoke all on function public.list_conversations(uuid)
  from public, anon;

grant execute on function public.list_conversations(uuid)
  to authenticated;

-- `(p_before_sent_at, p_before_id)`보다 앞선 메시지를 최신부터 `p_limit`개 골라 오래된 것부터
-- 돌려준다. 커서가 없으면 최신 페이지다. 커서 행을 찾지 않고 비교로 자르므로 커서의 메시지가
-- 사라져도 결과가 어긋나지 않는다. 더 앞선 메시지가 있는지는 호출하는 쪽이 한 개 더 요청해 안다.
create function public.list_messages(
  p_conversation_id uuid,
  p_before_sent_at timestamptz default null,
  p_before_id uuid default null,
  p_limit integer default 50
)
returns table (
  id uuid,
  sender_id bigint,
  body text,
  sent_at timestamptz,
  edited_at timestamptz,
  deleted boolean,
  reply_to_id uuid,
  reply_sender_id bigint,
  -- 답장 원문의 앞부분. 원문이 삭제됐으면 비운다.
  reply_body text,
  reply_deleted boolean,
  -- 내 메시지에서만 채운다. 이 메시지를 아직 읽지 않은 현재 멤버 수.
  unread_member_count integer
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  caller_profile_id bigint := private.current_profile_id();
  keys jsonb;
begin
  if caller_profile_id is null then
    raise exception 'accepted profile required'
      using errcode = '42501';
  end if;
  if (p_before_sent_at is null) <> (p_before_id is null) then
    raise exception 'cursor requires both sent_at and id'
      using errcode = '22023';
  end if;

  keys := private.message_keys();

  return query
  with period as (
    select member.joined_at, member.left_at
    from public.conversation_members as member
    where member.conversation_id = p_conversation_id
      and member.profile_id = caller_profile_id
  ), page as (
    select message.*
    from private.messages as message
    where message.conversation_id = p_conversation_id
      and (
        p_before_sent_at is null
        or (message.sent_at, message.id) < (p_before_sent_at, p_before_id)
      )
      and exists (
        select 1
        from period
        where message.sent_at >= period.joined_at
          and (period.left_at is null or message.sent_at < period.left_at)
      )
    order by message.sent_at desc, message.id desc
    limit least(greatest(coalesce(p_limit, 50), 1), 101)
  )
  select
    page.id,
    page.sender_id,
    case
      when page.deleted_at is null
        then private.decrypt_message_text(page.body_ciphertext, page.key_version, keys)
      else ''
    end,
    page.sent_at,
    page.edited_at,
    page.deleted_at is not null,
    original.id,
    original.sender_id,
    case
      when original.id is not null and original.deleted_at is null
        then left(
          private.decrypt_message_text(original.body_ciphertext, original.key_version, keys),
          200
        )
      when original.id is not null then ''
    end,
    original.deleted_at is not null,
    case
      when page.sender_id = caller_profile_id then (
        select count(*)::integer
        from public.conversation_members as other
        where other.conversation_id = p_conversation_id
          and other.profile_id <> caller_profile_id
          and other.left_at is null
          and other.joined_at <= page.sent_at
          and (other.last_read_sent_at, other.last_read_message_id) < (page.sent_at, page.id)
      )
    end
  from page
  -- 원문이 내 참여 기간 밖이면 인용을 붙이지 않는다. 참여 이전 메시지를 답장으로 엿보지 못하게 한다.
  left join private.messages as original
    on original.id = page.reply_to_id
    and exists (
      select 1
      from period
      where original.sent_at >= period.joined_at
        and (period.left_at is null or original.sent_at < period.left_at)
    )
  order by page.sent_at, page.id;
end;
$$;

revoke all on function public.list_messages(uuid, timestamptz, uuid, integer)
  from public, anon;

grant execute on function public.list_messages(uuid, timestamptz, uuid, integer)
  to authenticated;

-- 메시지를 보낸다. `p_message_id`는 클라이언트 UUID이며, 같은 값으로 다시 부르면 저장하지 않고
-- 처음 저장한 행을 돌려준다. 끝의 연속 줄바꿈은 지운다(기능 명세 §13.4). 본문 상한은 grapheme
-- 5,000자이지만 Postgres는 grapheme을 세지 못하므로, 클라이언트가 그 상한을 지키고 서버는 code
-- point 20,000개로 막는다. 보낸 사람의 읽음 위치는 이 메시지로 옮긴다.
create function public.send_message(
  p_conversation_id uuid,
  p_message_id uuid,
  p_body text,
  p_reply_to_id uuid default null
)
returns table (id uuid, sent_at timestamptz)
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_profile_id bigint := private.current_profile_id();
  normalized_body text := pg_catalog.regexp_replace(coalesce(p_body, ''), '[\r\n]+$', '');
  encrypted record;
  saved private.messages;
begin
  if caller_profile_id is null then
    raise exception 'accepted profile required'
      using errcode = '42501';
  end if;
  if p_message_id is null then
    raise exception 'message id required'
      using errcode = '22023';
  end if;

  select message.*
  into saved
  from private.messages as message
  where message.id = p_message_id;

  if saved.id is null then
    if normalized_body !~ '[^[:space:]]' or char_length(normalized_body) > 20000 then
      raise exception 'body must be 1 to 20000 characters'
        using errcode = '22023';
    end if;

    -- 나가기와 겹치지 않도록 내 현재 참여 기간을 잠근다.
    perform 1
    from public.conversation_members as member
    where member.conversation_id = p_conversation_id
      and member.profile_id = caller_profile_id
      and member.left_at is null
    for share;

    if not found then
      raise exception 'conversation member required'
        using errcode = '42501';
    end if;

    if p_reply_to_id is not null and not exists (
      select 1
      from private.messages as original
      join public.conversation_members as period
        on period.conversation_id = original.conversation_id
        and period.profile_id = caller_profile_id
        and original.sent_at >= period.joined_at
        and (period.left_at is null or original.sent_at < period.left_at)
      where original.id = p_reply_to_id
        and original.conversation_id = p_conversation_id
        and original.deleted_at is null
    ) then
      raise exception 'reply target unavailable'
        using errcode = '22023';
    end if;

    select * into encrypted
    from private.encrypt_message_text(normalized_body, private.message_keys());

    -- 전송 시각은 잠금과 키 읽기를 마친 지금이다. 트랜잭션 시작 시각(`now()`)을 쓰면 늦게 커밋된
    -- 메시지가 이미 읽은 위치보다 앞에 놓여 읽지 않은 수와 페이지 순서에서 빠질 수 있다.
    insert into private.messages (
      id, conversation_id, sender_id, sent_at, reply_to_id, body_ciphertext, key_version
    ) values (
      p_message_id,
      p_conversation_id,
      caller_profile_id,
      clock_timestamp(),
      p_reply_to_id,
      encrypted.ciphertext,
      encrypted.key_version
    )
    on conflict on constraint messages_pkey do nothing
    returning * into saved;

    if saved.id is not null then
      update public.conversation_members as member
      set last_read_sent_at = saved.sent_at,
        last_read_message_id = saved.id
      where member.conversation_id = p_conversation_id
        and member.profile_id = caller_profile_id
        and member.left_at is null
        and (member.last_read_sent_at, member.last_read_message_id) < (saved.sent_at, saved.id);
    else
      -- 같은 ID를 동시에 보낸 다른 요청이 먼저 저장했다.
      select message.*
      into saved
      from private.messages as message
      where message.id = p_message_id;
    end if;
  end if;

  if saved.sender_id is distinct from caller_profile_id
    or saved.conversation_id <> p_conversation_id then
    raise exception 'message id already used'
      using errcode = '23505';
  end if;

  return query select saved.id, saved.sent_at;
end;
$$;

revoke all on function public.send_message(uuid, uuid, text, uuid)
  from public, anon;

grant execute on function public.send_message(uuid, uuid, text, uuid)
  to authenticated;

-- 읽음 위치를 이 메시지로 옮긴다. 앞으로만 움직이며, 내 현재 참여 기간 밖의 메시지나 다른 대화의
-- 메시지면 아무것도 하지 않는다. 이 위치가 메시지 Push 억제의 근거다(알림 기술 설계 §11).
create function public.mark_conversation_read(
  p_conversation_id uuid,
  p_message_id uuid
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_profile_id bigint := private.current_profile_id();
begin
  if caller_profile_id is null then
    raise exception 'accepted profile required'
      using errcode = '42501';
  end if;

  update public.conversation_members as member
  set last_read_sent_at = target.sent_at,
    last_read_message_id = target.id
  from private.messages as target
  where target.id = p_message_id
    and target.conversation_id = p_conversation_id
    and member.conversation_id = p_conversation_id
    and member.profile_id = caller_profile_id
    and member.left_at is null
    and target.sent_at >= member.joined_at
    and (member.last_read_sent_at, member.last_read_message_id) < (target.sent_at, target.id);
end;
$$;

revoke all on function public.mark_conversation_read(uuid, uuid)
  from public, anon;

grant execute on function public.mark_conversation_read(uuid, uuid)
  to authenticated;
