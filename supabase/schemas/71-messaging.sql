create function public.list_message_changes(
  p_conversation_id uuid,
  p_since timestamptz,
  p_limit integer default 100
)
returns table (
  id uuid,
  sender_id bigint,
  body text,
  sent_at timestamptz,
  edited_at timestamptz,
  deleted boolean,
  reply_to_id uuid,
  reply_sender_id bigint,
  reply_body text,
  reply_deleted boolean,
