-- 앞뒤 공백을 지운다. `btrim`은 스페이스만 지워서 줄바꿈·탭만 적은 글이 빈 카드로 올라간다.
-- 클라이언트의 `String.prototype.trim()`과 맞춘다.
create function private.normalize_story_text(p_value text)
returns text
language sql
immutable
set search_path = ''
as $$
  select pg_catalog.regexp_replace(
    coalesce(p_value, ''), '^[[:space:]]+|[[:space:]]+$', '', 'g'
  );
$$;

revoke all on function private.normalize_story_text(text)
  from public;

-- 한 사람이 24시간 안에 올려 둘 수 있는 스토리 수의 상한. 아직 publish하지 않은 사진도 센다.
-- 상한이 없으면 업로드 경로를 반복 호출해 회수되기 전의 파일을 무제한으로 쌓을 수 있다.
create function private.story_writer_profile_id()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_profile_id bigint;
  active_count integer;
begin
  -- 쓰기는 재학생과 교사만 한다. 졸업생은 읽기만 하며, 그중에서도 교사 스토리만 본다
  -- (기능 명세 §17.6). 프로필 행을 잠가 동시에 올린 스토리가 상한을 함께 넘지 못하게 한다.
  select profile.id
  into caller_profile_id
  from public.profiles as profile
  where profile.auth_user_id = auth.uid()
    and profile.status = 'accepted'
    and profile.deleted_at is null
    and profile.type in ('student', 'teacher')
  -- `no key update`면 상한 검사끼리는 순서가 잡히면서도, 이 프로필을 참조하는 다른 행의 외래
  -- 키 검사(`key share`)는 막지 않는다.
  for no key update;

  if caller_profile_id is null then
    raise exception 'student or teacher profile required'
      using errcode = '42501';
  end if;

  select count(*)
  into active_count
  from public.stories as story
  where story.profile_id = caller_profile_id
    and (
      (story.status = 'ready' and story.expires_at > now())
      -- 미완성 업로드는 정리 작업이 지우는 48시간 동안 센다. 24시간만 세면 그 사이에 한도를
      -- 다시 채워 회수되지 않은 행을 두 배로 쌓을 수 있다.
      or (story.status = 'pending' and story.created_at > now() - interval '48 hours')
    );

  if active_count >= 20 then
    raise exception 'too many active stories'
      using errcode = '54000';
  end if;

  return caller_profile_id;
end;
$$;

revoke all on function private.story_writer_profile_id()
  from public;

-- 노출은 작성자의 유형으로만 판정한다. 교사 스토리는 모두가 보고, 재학생 스토리는 학교에 있는
-- 사람만 본다. 기수는 판정에 쓰지 않는다(기능 명세 §6.6). 목록과 Storage 읽기 정책이 같은
-- 판정을 쓰도록 한곳에 둔다.
create function private.can_read_story(p_story_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.stories as story
    join public.profiles as author
      on author.id = story.profile_id
      and author.status = 'accepted'
      and author.deleted_at is null
    join public.profiles as viewer
      on viewer.auth_user_id = auth.uid()
      and viewer.status = 'accepted'
      and viewer.deleted_at is null
    where story.id = p_story_id
      and story.status = 'ready'
      and story.expires_at > now()
      and (
        author.type = 'teacher'
        or (author.type = 'student' and viewer.type in ('student', 'teacher'))
      )
  );
$$;

revoke all on function private.can_read_story(bigint)
  from public;

