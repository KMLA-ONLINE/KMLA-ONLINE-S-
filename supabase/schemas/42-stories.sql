create function public.create_text_story(
  p_content text,
  p_background text,
  p_link_url text default null
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_profile_id bigint := private.story_writer_profile_id();
  created_id bigint;
  published timestamptz := now();
begin
  if char_length(private.normalize_story_text(p_content)) not between 1 and 100 then
    raise exception 'content must be 1 to 100 characters'
      using errcode = '22023';
  end if;

  insert into public.stories (
    profile_id, status, content, background, link_url, published_at, expires_at
  ) values (
    caller_profile_id,
    'ready',
    private.normalize_story_text(p_content),
    p_background,
    nullif(private.normalize_story_text(p_link_url), ''),
    published,
    published + interval '24 hours'
  )
  returning id into created_id;

  return created_id;
end;
$$;

revoke all on function public.create_text_story(text, text, text)
  from public, anon;

grant execute on function public.create_text_story(text, text, text)
  to authenticated;

create function public.prepare_image_story(
  p_size_bytes bigint,
  p_width integer,
  p_height integer,
  p_content text default '',
  p_link_url text default null
)
returns table (story_id bigint, object_path text, thumbnail_path text)
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_profile_id bigint := private.story_writer_profile_id();
  path text := auth.uid()::text || '/' || gen_random_uuid()::text;
  thumbnail text := path || '-thumb';
  created_id bigint;
begin
  if char_length(private.normalize_story_text(p_content)) > 100 then
    raise exception 'content must be at most 100 characters'
      using errcode = '22023';
  end if;
  -- 클라이언트 압축 정책(`screen`)과 버킷 용량 제한을 그대로 옮긴다.
  if p_size_bytes is null or p_size_bytes not between 1 and 4194304
    or p_width is null or p_height is null
    or least(p_width, p_height) < 1 or greatest(p_width, p_height) > 2048 then
    raise exception 'invalid normalized story image metadata'
      using errcode = '22023';
  end if;

  insert into public.stories (
    profile_id, content, image_path, thumbnail_path, image_size_bytes, image_width,
    image_height, link_url
  ) values (
    caller_profile_id,
    private.normalize_story_text(p_content),
    path,
    thumbnail,
    p_size_bytes,
    p_width,
    p_height,
    nullif(private.normalize_story_text(p_link_url), '')
  )
  returning id into created_id;

  return query select created_id, path, thumbnail;
end;
$$;

revoke all on function public.prepare_image_story(bigint, integer, integer, text, text)
  from public, anon;

grant execute on function public.prepare_image_story(bigint, integer, integer, text, text)
  to authenticated;

create function public.publish_image_story(p_story_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  caller_id uuid := auth.uid();
  story public.stories;
  object_record storage.objects;
  published timestamptz := now();
begin
  select item.*
  into story
  from public.stories as item
  join public.profiles as profile
    on profile.id = item.profile_id
  where item.id = p_story_id
    and profile.auth_user_id = caller_id
    and profile.status = 'accepted'
    and profile.deleted_at is null
  for update of item;

  if story.id is null then
    raise exception 'story owner required' using errcode = '42501';
  end if;
  if story.status <> 'pending' then
    raise exception 'story is not pending' using errcode = '55000';
  end if;

  select object.*
  into object_record
  from storage.objects as object
  where object.bucket_id = 'story-media'
    and object.name = story.image_path;

  if object_record.id is null then
    raise exception 'uploaded object not found' using errcode = 'P0002';
  end if;
  if object_record.owner_id is distinct from caller_id::text then
    raise exception 'uploaded object owner does not match' using errcode = '42501';
  end if;
  if nullif(object_record.metadata ->> 'size', '')::bigint is distinct from story.image_size_bytes
    or object_record.metadata ->> 'mimetype' is distinct from 'image/webp' then
    raise exception 'uploaded object metadata does not match' using errcode = '22023';
  end if;

  -- 축소본은 크기를 미리 알리지 않지만 레일이 작성자마다 받는 파일이라 클라이언트 압축
  -- 정책(`card`)의 상한을 여기서도 지킨다. 넘으면 모든 뷰어의 홈이 무거워진다.
  if not exists (
    select 1
    from storage.objects as object
    where object.bucket_id = 'story-media'
      and object.name = story.thumbnail_path
      and object.owner_id = caller_id::text
      and object.metadata ->> 'mimetype' = 'image/webp'
      and nullif(object.metadata ->> 'size', '')::bigint <= 524288
  ) then
    raise exception 'uploaded thumbnail not found' using errcode = 'P0002';
  end if;

  update public.stories
  set status = 'ready',
    published_at = published,
    expires_at = published + interval '24 hours'
  where id = story.id;
end;
$$;

revoke all on function public.publish_image_story(bigint)
  from public, anon;

grant execute on function public.publish_image_story(bigint)
  to authenticated;

-- 작성자별로 묶어 그리므로 작성자 순서와 작성자 안의 순서를 함께 준다. 재학생 뷰어에게는 같은
-- 기수 재학생을 앞에 두고, 그 안팎에서는 가장 최근 스토리가 새로운 작성자 순서다. 한 작성자의
-- 스토리는 올린 순서대로 넘겨 본다(기능 명세 §6.6).
create function public.list_active_stories()
returns table (
  story_id bigint,
  pub_id text,
  name text,
  avatar_path text,
  content text,
  background text,
  image_path text,
  thumbnail_path text,
  image_width integer,
  image_height integer,
  link_url text,
  published_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  with viewer as (
    select profile.type, profile.cohort
    from public.profiles as profile
    where profile.auth_user_id = auth.uid()
      and profile.status = 'accepted'
      and profile.deleted_at is null
  ), visible as (
    select
      story.*,
      author.pub_id,
      author.name,
      author.avatar_path,
      viewer.type = 'student'
        and author.type = 'student'
        and author.cohort = viewer.cohort as same_cohort
    from viewer
    cross join public.stories as story
    join public.profiles as author
      on author.id = story.profile_id
      and author.status = 'accepted'
      and author.deleted_at is null
    where story.status = 'ready'
      and story.expires_at > now()
      -- private.can_read_story와 같은 판정이다. 행마다 그 함수를 부르지 않으려고 풀어 쓴다.
      and (
        author.type = 'teacher'
        or (author.type = 'student' and viewer.type in ('student', 'teacher'))
      )
  )
  select
    visible.id,
    visible.pub_id,
    visible.name,
    visible.avatar_path,
    visible.content,
    visible.background,
    visible.image_path,
    visible.thumbnail_path,
    visible.image_width,
    visible.image_height,
    visible.link_url,
    visible.published_at
  from visible
  order by
    visible.same_cohort desc,
    max(visible.published_at) over (partition by visible.profile_id) desc,
    visible.profile_id,
    visible.published_at,
    visible.id;
$$;

revoke all on function public.list_active_stories()
  from public, anon;

grant execute on function public.list_active_stories()
  to authenticated;

-- 사용자 행동이 계기인 삭제라 그 자리에서 지운다. 행을 지우는 문장이 이미지 경로를 정리
-- 큐로 옮기므로 경로를 잃고 object만 남는 순간이 없다.
create function public.delete_my_story(p_story_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  found_count integer;
begin
  with deleted as (
    delete from public.stories as story
    using public.profiles as profile
    where story.id = p_story_id
      and profile.id = story.profile_id
      and profile.auth_user_id = auth.uid()
      and profile.status = 'accepted'
      and profile.deleted_at is null
    returning story.image_path, story.thumbnail_path
  ), queued as (
    insert into private.storage_cleanup_queue as queue (bucket, object_path, reason)
    select 'story-media', path.object_path, 'story_media'
    from deleted
    cross join lateral (
      values (deleted.image_path), (deleted.thumbnail_path)
    ) as path(object_path)
    where path.object_path is not null
    on conflict (bucket, object_path) do update
      set dry_run = queue.dry_run and excluded.dry_run
  )
  select count(*) into found_count from deleted;

  if found_count = 0 then
    raise exception 'story owner required' using errcode = '42501';
  end if;
end;
$$;

revoke all on function public.delete_my_story(bigint)
  from public, anon;

grant execute on function public.delete_my_story(bigint)
  to authenticated;
