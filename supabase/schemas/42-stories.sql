-- 그 스토리를 보는 사람의 프로필. 작성자 본인이면 `null`이다. 볼 수 없는 스토리는 없는 것과
-- 같이 다뤄 있는지조차 알리지 않는다.
create function private.story_audience_profile_id(p_story_id bigint)
returns bigint
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  viewer_id bigint;
  author_id bigint;
begin
  if not private.can_read_story(p_story_id) then
    raise exception 'story not found' using errcode = 'P0002';
  end if;

  select profile.id
  into viewer_id
  from public.profiles as profile
  where profile.auth_user_id = auth.uid();

  select story.profile_id
  into author_id
  from public.stories as story
  where story.id = p_story_id;

  return nullif(viewer_id, author_id);
end;
$$;

revoke all on function private.story_audience_profile_id(bigint)
  from public;

-- 처음 본 때만 남긴다. 작성자가 자기 스토리를 여는 것은 기록하지 않는다.
create function public.mark_story_viewed(p_story_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  viewer_id bigint := private.story_audience_profile_id(p_story_id);
begin
  if viewer_id is null then
    return;
  end if;

  insert into public.story_views (story_id, profile_id)
  values (p_story_id, viewer_id)
  on conflict do nothing;
end;
$$;

