-- 스토리는 올린 때부터 24시간 보이는 카드다. 한 장은 사진 스토리이거나 배경색 위의 글
-- 스토리이고, 둘 다 링크를 하나 달 수 있다(기능 명세 §17.6).
--
-- 사진 스토리는 다른 이미지 업로드와 같은 prepare → upload → publish 순서를 따른다.
-- prepare가 `pending` 행을 만들어 업로드할 정확한 경로를 정하고, publish가 object를 확인한 뒤
-- `ready`로 올린다. 글 스토리는 object가 없으므로 곧바로 `ready`로 만든다.

create type public.story_status as enum ('pending', 'ready');

-- 재학생 작성자가 고르는 공개 범위(기능 명세 §17.6). `everyone`은 작성자 유형의 기본 노출을
-- 따르고, `students`는 재학생만, `cohort`는 같은 기수 재학생만 본다. 교사의 스토리는 늘
-- `everyone`이다.
create type public.story_audience as enum ('everyone', 'students', 'cohort');

-- 글과 링크를 캔버스 어디에 얼마나 크게 놓았는지. 9:16 캔버스 안의 비율 좌표(요소의 중심)와
-- 기본 크기에 대한 배율이다. 키가 없으면 그 요소는 기본 자리에 그린다. 모든 뷰어가 같은 자리에
-- 그려야 하므로 모양을 여기서 지킨다. 형식이 틀린 값에서 캐스트가 터지지 않도록 `case`로
-- 타입을 먼저 본다.
create function private.is_story_layout(p_layout jsonb)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select case
    when pg_catalog.jsonb_typeof(p_layout) <> 'object' then false
    when (p_layout - array['text', 'link']) <> '{}'::jsonb then false
    else not exists (
      select 1
      from pg_catalog.jsonb_each(p_layout) as item(key, value)
      where not case
        when pg_catalog.jsonb_typeof(item.value) <> 'object' then false
        when (item.value - array['x', 'y', 'scale']) <> '{}'::jsonb then false
        when pg_catalog.jsonb_typeof(item.value -> 'x') is distinct from 'number'
          or pg_catalog.jsonb_typeof(item.value -> 'y') is distinct from 'number'
          or pg_catalog.jsonb_typeof(item.value -> 'scale') is distinct from 'number'
          then false
        else (item.value ->> 'x')::numeric between 0 and 1
          and (item.value ->> 'y')::numeric between 0 and 1
          and (item.value ->> 'scale')::numeric between 0.5 and 2.5
      end
    )
  end;
$$;

revoke all on function private.is_story_layout(jsonb)
  from public;

create table public.stories (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  status public.story_status not null default 'pending',
  content text not null default '',
  -- 글 스토리의 배경. 사진 스토리에는 없다. 값은 클라이언트의 색 목록과 같은 키다.
  background text,
  image_path text unique,
  -- 레일 카드에 까는 축소본. 원본은 뷰어에서 그 장을 열 때만 받는다.
  thumbnail_path text unique,
  image_size_bytes bigint,
  image_width integer,
  image_height integer,
  link_url text,
  layout jsonb,
  audience public.story_audience not null default 'everyone',
  created_at timestamptz not null default now(),
  published_at timestamptz,
  expires_at timestamptz,
  constraint stories_content_length
    check (
      char_length(content) <= 100
      and content !~ '^[[:space:]]'
      and content !~ '[[:space:]]$'
    ),
  constraint stories_background_check
    check (background in ('blue', 'purple', 'pink', 'orange', 'green', 'dark')),
  constraint stories_link_url_check
    check (
      link_url is null
      or (char_length(link_url) <= 2048 and link_url ~ '^https?://[^[:space:]]+$')
    ),
  -- 없는 글이나 링크의 자리는 둘 수 없다.
  constraint stories_layout_check
    check (
      layout is null
      or (
        private.is_story_layout(layout)
        and (not layout ? 'text' or content <> '')
        and (not layout ? 'link' or link_url is not null)
      )
    ),
  -- 사진과 배경은 정확히 하나다. 글 스토리는 글이 곧 내용이므로 비울 수 없다.
  constraint stories_kind_check
    check (
      (
        image_path is not null
        and thumbnail_path is not null
        and background is null
        and image_size_bytes is not null
        and image_width > 0
        and image_height > 0
      )
      or (
        image_path is null
        and thumbnail_path is null
        and background is not null
        and image_size_bytes is null
        and image_width is null
        and image_height is null
        and content ~ '[^[:space:]]'
      )
    ),
  constraint stories_publication_check
    check (
      (status = 'pending' and published_at is null and expires_at is null)
      or (
        status = 'ready'
        and published_at is not null
        and expires_at = published_at + interval '24 hours'
      )
    )
);

