create type public.story_status as enum ('pending', 'ready');

create table public.stories (
  id bigint generated by default as identity primary key,
  profile_id bigint not null references public.profiles(id) on delete cascade,
  status public.story_status not null default 'pending',
  content text not null default '',
  -- 글 스토리의 배경. 사진 스토리에는 없다. 값은 클라이언트의 색 목록과 같은 키다.
  background text,
  image_path text unique,
  -- 레일 카드에 까는 축소본. 원본은 뷰어에서 그 장을 열 때만 받는다.
  thumbnail_path text unique,
  image_size_bytes bigint,
  image_width integer,
  image_height integer,
  link_url text,
  created_at timestamptz not null default now(),
  published_at timestamptz,
  expires_at timestamptz,
  constraint stories_content_length
    check (char_length(content) <= 100 and content = btrim(content)),
  constraint stories_background_check
    check (background in ('blue', 'purple', 'pink', 'orange', 'green', 'dark')),
  constraint stories_link_url_check
    check (
      link_url is null
      or (char_length(link_url) <= 2048 and link_url ~ '^https?://[^[:space:]]+$')
    ),
  -- 사진과 배경은 정확히 하나다. 글 스토리는 글이 곧 내용이므로 비울 수 없다.
  constraint stories_kind_check
    check (
      (
        image_path is not null
        and thumbnail_path is not null
        and background is null
        and image_size_bytes is not null
        and image_width > 0
        and image_height > 0
      )
      or (
        image_path is null
        and thumbnail_path is null
        and background is not null
        and image_size_bytes is null
        and image_width is null
        and image_height is null
        and char_length(content) >= 1
      )
    ),
  constraint stories_publication_check
    check (
      (status = 'pending' and published_at is null and expires_at is null)
      or (
        status = 'ready'
        and published_at is not null
        and expires_at = published_at + interval '24 hours'
      )
    )
);

