CREATE OR REPLACE FUNCTION private.decrypt_message_text (
  p_ciphertext  bytea,
  p_key_version smallint,
  p_keys        jsonb
)
  RETURNS text
  LANGUAGE sql
  IMMUTABLE
  SET search_path TO ''
  AS $function$
  select extensions.pgp_sym_decrypt(p_ciphertext, p_keys ->> p_key_version::text);
$function$;

CREATE OR REPLACE FUNCTION private.encrypt_message_text (
  p_text text,
  p_keys jsonb
)
  RETURNS TABLE (
    ciphertext  bytea,
    key_version smallint
  )
  LANGUAGE sql
  SET search_path TO ''
  AS $function$
  select
    extensions.pgp_sym_encrypt(
      p_text, p_keys ->> current_key.version::text, 's2k-mode=1, cipher-algo=aes256'
    ),
    current_key.version
  from (
    select max(key::smallint) as version
    from jsonb_object_keys(p_keys) as key
  ) as current_key;
$function$;

CREATE OR REPLACE FUNCTION private.message_keys()
  RETURNS jsonb
  LANGUAGE plpgsql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  keys jsonb;
begin
  select jsonb_object_agg(
    substring(secret.name from '^message_key_v([0-9]+)$'),
    secret.decrypted_secret
  )
  into keys
  from vault.decrypted_secrets as secret
  where secret.name ~ '^message_key_v[0-9]+$';

  if keys is null then
    raise exception 'message encryption key missing'
      using errcode = '55000';
  end if;

  return keys;
end;
$function$;

CREATE OR REPLACE FUNCTION public.list_conversations (
  p_conversation_id uuid DEFAULT NULL::uuid
)
  RETURNS TABLE (
    conversation_id        uuid,
    type                   public.conversation_type,
    name                   text,
    viewer_id              bigint,
    participants           jsonb,
    last_message_id        uuid,
    last_message_sender_id bigint,
    last_message_body      text,
    last_message_sent_at   timestamp with time zone,
    last_message_deleted   boolean,
    unread_count           integer,
    muted                  boolean
  )
  LANGUAGE plpgsql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  caller_profile_id bigint := private.current_profile_id();
  keys jsonb;
begin
  if caller_profile_id is null then
    raise exception 'accepted profile required'
      using errcode = '42501';
  end if;

  keys := private.message_keys();

  return query
  with latest_period as (
    -- 대화마다 가장 최근 참여 기간. 읽음 위치와 알림 설정은 이 행의 값을 쓴다.
    select distinct on (member.conversation_id) member.*
    from public.conversation_members as member
    where member.profile_id = caller_profile_id
      and (p_conversation_id is null or member.conversation_id = p_conversation_id)
    order by member.conversation_id, member.joined_at desc
  )
  select
    conversation.id,
    conversation.type,
    coalesce(conversation.name, counterpart.name),
    caller_profile_id,
    coalesce(members.list, '[]'::jsonb),
    last_message.id,
    last_message.sender_id,
    case
      when last_message.deleted_at is null and last_message.id is not null
        then private.decrypt_message_text(
          last_message.body_ciphertext, last_message.key_version, keys
        )
    end,
    last_message.sent_at,
    last_message.deleted_at is not null,
    coalesce(unread.count, 0)::integer,
    coalesce(latest_period.muted_until > now(), false)
  from latest_period
  join public.conversations as conversation
    on conversation.id = latest_period.conversation_id
  left join public.profiles as counterpart
    on conversation.type = 'direct'
    and counterpart.id = case
      when conversation.direct_profile_low = caller_profile_id
        then conversation.direct_profile_high
      else conversation.direct_profile_low
    end
  left join lateral (
    select jsonb_agg(
      jsonb_build_object(
        'id', profile.id,
        'name', profile.name,
        'avatar_path', profile.avatar_path
      )
      order by member.joined_at, member.id
    ) as list
    from public.conversation_members as member
    join public.profiles as profile on profile.id = member.profile_id
    where member.conversation_id = conversation.id
      and member.left_at is null
  ) as members on true
  left join lateral (
    select message.*
    from private.messages as message
    where message.conversation_id = conversation.id
      and exists (
        select 1
        from public.conversation_members as period
        where period.conversation_id = conversation.id
          and period.profile_id = caller_profile_id
          and message.sent_at >= period.joined_at
          and (period.left_at is null or message.sent_at < period.left_at)
      )
    order by message.sent_at desc, message.id desc
    limit 1
  ) as last_message on true
  left join lateral (
    select count(*) as count
    from private.messages as message
    where message.conversation_id = conversation.id
      and message.sender_id is distinct from caller_profile_id
      and message.deleted_at is null
      and (message.sent_at, message.id)
        > (latest_period.last_read_sent_at, latest_period.last_read_message_id)
      and exists (
        select 1
        from public.conversation_members as period
        where period.conversation_id = conversation.id
          and period.profile_id = caller_profile_id
          and message.sent_at >= period.joined_at
          and (period.left_at is null or message.sent_at < period.left_at)
      )
  ) as unread on true
  order by last_message.sent_at desc nulls last, conversation.created_at desc, conversation.id;
end;
$function$;

REVOKE ALL ON FUNCTION "public"."list_conversations"(uuid) FROM PUBLIC, "anon";

CREATE OR REPLACE FUNCTION public.list_messages (
  p_conversation_id uuid,
  p_before_sent_at  timestamp with time zone DEFAULT NULL::timestamp WITH time zone,
  p_before_id       uuid                     DEFAULT NULL::uuid,
  p_limit           integer                  DEFAULT 50
)
  RETURNS TABLE (
    id                  uuid,
    sender_id           bigint,
    body                text,
    sent_at             timestamp with time zone,
    edited_at           timestamp with time zone,
    deleted             boolean,
    reply_to_id         uuid,
    reply_sender_id     bigint,
    reply_body          text,
    reply_deleted       boolean,
    unread_member_count integer
  )
  LANGUAGE plpgsql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  caller_profile_id bigint := private.current_profile_id();
  keys jsonb;
begin
  if caller_profile_id is null then
    raise exception 'accepted profile required'
      using errcode = '42501';
  end if;
  if (p_before_sent_at is null) <> (p_before_id is null) then
    raise exception 'cursor requires both sent_at and id'
      using errcode = '22023';
  end if;

  keys := private.message_keys();

  return query
  with period as (
    select member.joined_at, member.left_at
    from public.conversation_members as member
    where member.conversation_id = p_conversation_id
      and member.profile_id = caller_profile_id
  ), page as (
    select message.*
    from private.messages as message
    where message.conversation_id = p_conversation_id
      and (
        p_before_sent_at is null
        or (message.sent_at, message.id) < (p_before_sent_at, p_before_id)
      )
      and exists (
        select 1
        from period
        where message.sent_at >= period.joined_at
          and (period.left_at is null or message.sent_at < period.left_at)
      )
    order by message.sent_at desc, message.id desc
    limit least(greatest(coalesce(p_limit, 50), 1), 101)
  )
  select
    page.id,
    page.sender_id,
    case
      when page.deleted_at is null
        then private.decrypt_message_text(page.body_ciphertext, page.key_version, keys)
      else ''
    end,
    page.sent_at,
    page.edited_at,
    page.deleted_at is not null,
    original.id,
    original.sender_id,
    case
      when original.id is not null and original.deleted_at is null
        then left(
          private.decrypt_message_text(original.body_ciphertext, original.key_version, keys),
          200
        )
      when original.id is not null then ''
    end,
    original.deleted_at is not null,
    case
      when page.sender_id = caller_profile_id then (
        select count(*)::integer
        from public.conversation_members as other
        where other.conversation_id = p_conversation_id
          and other.profile_id <> caller_profile_id
          and other.left_at is null
          and other.joined_at <= page.sent_at
          and (other.last_read_sent_at, other.last_read_message_id) < (page.sent_at, page.id)
      )
    end
  from page
  -- 원문이 내 참여 기간 밖이면 인용을 붙이지 않는다. 참여 이전 메시지를 답장으로 엿보지 못하게 한다.
  left join private.messages as original
    on original.id = page.reply_to_id
    and exists (
      select 1
      from period
      where original.sent_at >= period.joined_at
        and (period.left_at is null or original.sent_at < period.left_at)
    )
  order by page.sent_at, page.id;
end;
$function$;

